import { useId, useState } from 'react'
import type { CSSProperties } from 'react'
import sampleOriginal from './assets/mirror-original.webp'
import sampleResult from './assets/mirror-result.webp'
import './Mirror.css'

export function TryFitMirror({ original, result }: { original: string; result: string }) {
  const [position, setPosition] = useState(50)
  const sliderId = useId()

  return (
    <div className="tryfit-mirror">
      <div className="mirror-frame" style={{ '--mirror-position': `${position}%` } as CSSProperties}>
        <img className="mirror-result" src={result} alt="AI try-on result" loading="lazy" />
        <img className="mirror-original" src={original} alt="Original person photo" loading="lazy" />
        <span className="mirror-divider" aria-hidden="true" />
      </div>
      <div className="mirror-controls">
        <label className="visually-hidden" htmlFor={sliderId}>Compare original photo and AI try-on</label>
        <div className="mirror-labels" aria-hidden="true"><span>Original photo</span><span>AI try-on</span></div>
        <input
          id={sliderId}
          type="range"
          min={0}
          max={100}
          value={position}
          aria-valuetext={`${position}% original photo visible`}
          onChange={event => setPosition(Number(event.target.value))}
        />
      </div>
    </div>
  )
}

export function TryFitSample() {
  return (
    <details className="mirror-sample">
      <summary><span>Try a sample</span><span className="mirror-disclosure" aria-hidden="true">↗</span></summary>
      <div className="mirror-sample-content">
        <div className="mirror-sample-copy">
          <p className="mirror-sample-label">Pre-generated sample</p>
          <h3>The TryFit Mirror</h3>
          <p>Move the slider to compare the original photo with a cardigan preview generated by CatVTON in Colab.</p>
          <small>Original photo from the <a href="https://github.com/Zheng-Chong/CatVTON">CatVTON demo</a> · <a href="https://creativecommons.org/licenses/by-nc-sa/4.0/">CC BY-NC-SA 4.0</a></small>
        </div>
        <TryFitMirror original={sampleOriginal} result={sampleResult} />
      </div>
    </details>
  )
}
